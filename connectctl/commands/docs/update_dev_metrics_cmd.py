from __future__ import annotations

import argparse

from ...logging_utils import get_logger
from ...services.docs.update_dev_metrics_service import UpdateDevMetricsService


def cmd_docs_update_dev_metrics(args: argparse.Namespace, *, ctx, logger=None) -> int:
    log = get_logger(logger or getattr(ctx, "logger", None))
    svc = UpdateDevMetricsService(ctx=ctx, logger=log)
    return int(svc.run(args))


def register_parser(docs_sub: argparse._SubParsersAction) -> argparse.ArgumentParser:
    p = docs_sub.add_parser(
        "update-dev-metrics",
        help=(
            "Update autogenerated engineering metrics docs "
            "(LOC/SLOC, coupling/cohesion) and optionally verify freshness"
        ),
    )
    p.add_argument(
        "--check",
        action="store_true",
        help="Only verify that generated docs are up to date (do not rewrite files).",
    )
    p.add_argument(
        "--target",
        choices=["all", "md"],
        default="all",
        help="Which docs to update/check: all (default) | md",
    )
    p.add_argument(
        "--docs-dir",
        default="docs",
        help="Docs directory relative to the repo root (default: docs)",
    )
    p.add_argument(
        "--top",
        type=int,
        default=15,
        help="How many largest modules to show in the size table (default: 15)",
    )
    p.set_defaults(func=cmd_docs_update_dev_metrics, requires_config=False)
    return p
