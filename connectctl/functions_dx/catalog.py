from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from ..settings_models import Settings
from .coverage import FunctionCoverageService, VariableCoverageService


@dataclass(frozen=True)
class FunctionCatalogService:
    """Generates self-service Markdown docs from function coverage payloads."""

    settings: Settings

    def generate(self, *, output_file: Path) -> dict[str, Any]:
        coverage = FunctionCoverageService(self.settings).report()
        markdown = _functions_markdown(coverage)
        target = _target_path(self.settings.repo.root, output_file)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(markdown, encoding="utf-8")
        return {
            "kind": "function_catalog",
            "status": "created",
            "path": _relative(self.settings.repo.root, target),
            "coverage": coverage["summary"],
        }


@dataclass(frozen=True)
class VariableCatalogService:
    """Generates self-service Markdown docs from variable coverage payloads."""

    settings: Settings
    schema_path: str | None = None

    def generate(self, *, output_file: Path) -> dict[str, Any]:
        coverage = VariableCoverageService(
            self.settings, schema_path=self.schema_path
        ).report()
        markdown = _vars_markdown(coverage)
        target = _target_path(self.settings.repo.root, output_file)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(markdown, encoding="utf-8")
        return {
            "kind": "variable_catalog",
            "status": "created",
            "path": _relative(self.settings.repo.root, target),
            "coverage": coverage["summary"],
        }


def _functions_markdown(coverage: dict[str, Any]) -> str:
    lines = [
        "# BKKT Function Catalog",
        "",
        "Autogenerated from `bkkt functions coverage`.",
        "",
        "| Function | Package | Source | Usages | Contracts | Lifecycle | Status |",
        "|---|---|---|---:|---|---|---|",
    ]
    for item in coverage["items"]:
        lifecycle = _lifecycle_label(item.get("lifecycle", {}))
        contracts = item["contract_tests"]
        lines.append(
            "| "
            + " | ".join(
                [
                    f"`{item['name']}`",
                    _cell(item.get("package") or "-"),
                    _cell(item.get("source") or "-"),
                    str(item.get("usage_count", 0)),
                    _cell(f"{contracts['status']} ({contracts['total']})"),
                    _cell(lifecycle),
                    _cell(item.get("status") or "-"),
                ]
            )
            + " |"
        )
    lines.extend(["", "Generated by `bkkt functions catalog generate`.", ""])
    return "\n".join(lines)


def _vars_markdown(coverage: dict[str, Any]) -> str:
    lines = [
        "# BKKT Variable Catalog",
        "",
        "Autogenerated from `bkkt vars coverage`.",
        "",
        "| Variable | Usages | Schema | Flags | Replacement | Status |",
        "|---|---:|---|---|---|---|",
    ]
    for item in coverage["items"]:
        schema = item["schema_entry"]
        flags = _var_flags(schema)
        replacement = schema.get("replacement") or "-"
        lines.append(
            "| "
            + " | ".join(
                [
                    f"`{item['key']}`",
                    str(item.get("usage_count", 0)),
                    _cell(schema.get("status") or "-"),
                    _cell(flags),
                    _cell(replacement),
                    _cell(item.get("status") or "-"),
                ]
            )
            + " |"
        )
    lines.extend(["", "Generated by `bkkt vars catalog generate`.", ""])
    return "\n".join(lines)


def _lifecycle_label(lifecycle: dict[str, Any]) -> str:
    if not lifecycle.get("deprecated"):
        return "-"
    parts = ["deprecated"]
    if lifecycle.get("replacement"):
        parts.append(f"replacement={lifecycle['replacement']}")
    if lifecycle.get("remove_after"):
        parts.append(f"remove_after={lifecycle['remove_after']}")
    return ", ".join(parts)


def _var_flags(schema: dict[str, Any]) -> str:
    flags = []
    if schema.get("required"):
        flags.append("required")
    if schema.get("sensitive"):
        flags.append("sensitive")
    if schema.get("deprecated"):
        flags.append("deprecated")
    return ", ".join(flags) or "-"


def _target_path(repo_root: Path, output_file: Path) -> Path:
    return output_file if output_file.is_absolute() else repo_root / output_file


def _relative(repo_root: Path, path: Path) -> str:
    try:
        return path.resolve().relative_to(repo_root.resolve()).as_posix()
    except ValueError:
        return str(path)


def _cell(value: Any) -> str:
    return str(value).replace("|", "\\|")
